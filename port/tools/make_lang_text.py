#!/usr/bin/env python3
"""Turns tools/text/text_catalogue.csv into port/src/lang_text.h (the Language setting's text).

Run after editing the CSV:
    python3 port/tools/make_lang_text.py
Then rebuild, and check how it fits with
    ./build/monsterparty --lang-report
which lays every story page, speech bubble and screen text out exactly as the game will show it
and lists anything that doesn't fit or has no tile in the game's font.

Only two columns are used: "US ROM JA" (the US release with Language = 日本語) and "JP ROM EN" (the
prototype with Language = English). The other two are the games' own text, kept for reference.
Rows whose ID starts with "title." are left out (the title screen isn't translated).
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, '..', '..', 'tools', 'text', 'text_catalogue.csv')
OUT = os.path.join(HERE, '..', 'src', 'lang_text.h')


def cstr(s):
    """A C++ UTF-8 string literal (u8 would make it char8_t in C++20; the port is C++17, so plain)."""
    out = '"'
    for ch in s:
        if ch == '\\': out += '\\\\'
        elif ch == '"': out += '\\"'
        elif ch == '\n': out += '\\n'
        elif ch == '\r': continue
        else: out += ch
    return out + '"'


rows = list(csv.reader(open(CSV, encoding='utf-8-sig')))
head = rows[0]
col = {name: i for i, name in enumerate(head)}
items = []
for r in rows[1:]:
    if not r or not r[0].strip() or r[0].startswith('title.'):
        continue
    get = lambda name: r[col[name]] if col[name] < len(r) else ''
    items.append((r[0].strip(), get('US ROM JA'), get('JP ROM EN')))

out = ['// Generated by port/tools/make_lang_text.py from tools/text/text_catalogue.csv. Do not edit;',
       '// edit the CSV and run the script again.',
       '//',
       '// The Language setting\'s text (language.cpp): "US ROM JA" is the US release in Japanese,',
       '// "JP ROM EN" the prototype in English. Line breaks are as typed in the CSV.',
       '#pragma once',
       '',
       'namespace lang_text {',
       'struct Item { const char* id; const char* us_ja; const char* jp_en; };',
       f'inline constexpr Item items[{len(items)}] = {{']
for id_, ja, en in items:
    out.append(f'    {{{cstr(id_)},')
    out.append(f'     {cstr(ja)},')
    out.append(f'     {cstr(en)}}},')
out.append('};')
out.append('}  // namespace lang_text')
open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'wrote {OUT} ({len(items)} items)')
