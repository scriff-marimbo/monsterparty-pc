#!/usr/bin/env python3
"""Turns port/graphics/font_extra.png into src/font_extra.h: the port's own font tiles.

The Language setting draws the text with the games' own font, taken from the two ROMs at run time
(language.cpp). A few characters the translations use aren't in either ROM; they're drawn here
instead, in the same style. These are the user's own drawings, not graphics from the ROM.

font_extra.png is a strip of 8 x 8 cells, one character per cell, in the order of CHARS below.
Colours: white = the font's background (colour 1), black = colour 0, light grey = colour 2,
anything else (e.g. the blue it's drawn in) = the letters' colour (colour 3).
To add a character: widen the PNG by 8 pixels, draw it in the new cell, add it to CHARS, and run
    python3 port/tools/make_font_extra.py
"""
import os
from PIL import Image

CHARS = 'マニ…:'

HERE = os.path.dirname(os.path.abspath(__file__))
PNG = os.path.join(HERE, '..', 'graphics', 'font_extra.png')
OUT = os.path.join(HERE, '..', 'src', 'font_extra.h')


def colour(rgb):
    r, g, b = rgb[:3]
    if (r, g, b) == (255, 255, 255): return 1
    if (r, g, b) == (0, 0, 0): return 0
    if r == g == b: return 2
    return 3


im = Image.open(PNG).convert('RGB')
assert im.height == 8 and im.width >= 8 * len(CHARS), f'{PNG}: needs {len(CHARS)} cells of 8 x 8'
out = ['// Generated by port/tools/make_font_extra.py from port/graphics/font_extra.png. Do not edit;',
       '// edit the PNG and run the script again.',
       '//',
       "// Font tiles drawn by the port itself (the user's own art, not from the ROM): characters the",
       "// Language setting's text needs that neither game's font has. Same format as the game's CHR",
       '// tiles: 8 bytes of bit plane 0, then 8 of bit plane 1 (colour 1 = background, 3 = letters).',
       '#pragma once',
       '#include <cstdint>',
       '',
       'namespace font_extra {',
       'struct Glyph { const char* ch; uint8_t tile[16]; };   // ch: one UTF-8 character',
       f'inline constexpr Glyph glyphs[{len(CHARS)}] = {{']
for i, ch in enumerate(CHARS):
    lo, hi = [], []
    for y in range(8):
        a = b = 0
        for x in range(8):
            v = colour(im.getpixel((i * 8 + x, y)))
            a = a << 1 | (v & 1)
            b = b << 1 | (v >> 1)
        lo.append(a); hi.append(b)
    out.append(f'    {{"{ch}", {{' + ', '.join(f'0x{v:02X}' for v in lo + hi) + '}},')
out.append('};')
out.append('}  // namespace font_extra')
open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'wrote {OUT}')
