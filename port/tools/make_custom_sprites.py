#!/usr/bin/env python3
"""Turns the port's own sprite art (port/graphics/*.png) into src/custom_sprites.h.

These are the user's own drawings, not graphics from the ROM. Run after editing a PNG:
    python3 port/tools/make_custom_sprites.py
Each image is stored as rows of characters, one per pixel, with a colour table; '.' is transparent.
The colours are stored as NES colour numbers ($00-$3F), so the sprites follow the chosen palette like
the game's own: each PNG colour becomes the NES colour nearest to it over the bundled colour
palettes (port/palettes), which picks the same colours as the game's (e.g. the Totem Pole's arena
sprite palettes $36 $27 $19, $29 $28 $1A, $29 $26 $27, $17 $16). Within one image each colour gets a
different NES colour (the next nearest, if two would land on the same one).
"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
GFX = os.path.join(HERE, '..', 'graphics')
OUT = os.path.join(HERE, '..', 'src', 'custom_sprites.h')

# name in C++, file, which black pixels are transparent ('corners' = only the four corners, 'all'),
# what it's for
SPRITES = [
    ('TOTEM_HEAD', 'totem_head.png', 'corners',
     "the Totem Pole's head shot (16 x 16, facing right; drawn flipped when it flies left)"),
    ('TOTEM_FRAME2', 'totem_frame2.png', 'all',
     "the 'finished' Totem Pole's 2nd animation frame (drawn bottom-aligned on his own sprite)"),
    ('FAST_FORWARD', 'fastforward.png', 'all',
     "shown in the upper left corner while fast forward (Tab) is on"),
    ('R6_MARKED_DOOR', 'r6_markeddoor.png', 'all',
     "trainer Mark Round 6 Doors: a door entered this run (16 x 32, drawn over the room's door; '.' = the backdrop)"),
]
CHARS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'
REFERENCE = ['NES NTSC.pal', 'Soft.pal']   # the bundled colour ones


def load_pal(path):
    d = open(path, 'rb').read()
    if d.startswith(b'JASC'):
        lines = [l for l in d.decode().split('\n')[3:] if l.strip()]
        return [tuple(map(int, l.split()[:3])) for l in lines][:64]
    return [tuple(d[i * 3:i * 3 + 3]) for i in range(64)]


PALS = [load_pal(os.path.join(HERE, '..', 'palettes', p)) for p in REFERENCE]


def nes_colour(rgb, taken=()):
    """The NES colour number nearest to rgb, summed over the reference palettes, leaving out the
    ones already given to the image's other colours (so two close shades don't become one)."""
    def cost(i):
        return sum(sum((a - b) ** 2 for a, b in zip(rgb, pal[i])) for pal in PALS)
    if rgb == (0, 0, 0):
        return 0x0F                                       # the black the game uses
    return min((i for i in range(64) if i not in taken), key=cost)


def nes_colours(colours):
    """nes_colour for each of an image's colours, each a different NES colour"""
    out = []
    for c in colours:
        out.append(nes_colour(c, out))
    return out

out = ['// Generated by port/tools/make_custom_sprites.py from port/graphics/*.png. Do not edit;',
       '// edit the PNGs and run the script again.',
       '//',
       "// Sprites drawn by the port itself (the user's own art, not from the ROM's CHR): the launcher's",
       "// 'Finished' Totem Pole boss option (prototype; drawn by Nes::render_frame), the fast forward",
       "// icon (drawn by main.cpp) and the Mark Round 6 Doors trainer's door (drawn by Nes::render_frame).",
       '#pragma once',
       '#include <cstdint>',
       '',
       'namespace custom_sprite {',
       'struct Sprite {',
       '    int w, h;',
       "    const char* const* rows;    // h strings of w characters: '.' transparent, else an index into colours",
       '    const uint8_t* colours;     // NES colour numbers ($00-$3F), for the characters a, b, c, ...',
       '    uint8_t colour(char c) const { return colours[c - \'a\']; }',
       '};',
       '']
for name, fn, transparent, what in SPRITES:
    im = Image.open(os.path.join(GFX, fn)).convert('RGBA')
    w, h = im.size
    colours, rows = [], []
    for y in range(h):
        row = ''
        for x in range(w):
            r, g, b, a = im.getpixel((x, y))
            corner = x in (0, w - 1) and y in (0, h - 1)
            if a < 128 or ((r, g, b) == (0, 0, 0) and (transparent == 'all' or corner)):
                row += '.'
                continue
            if (r, g, b) not in colours:
                colours.append((r, g, b))
            row += CHARS[colours.index((r, g, b))]
        rows.append(row)
    lower = name.lower()
    out.append(f'// {fn}: {what}')
    out.append(f'inline constexpr const char* {lower}_rows[{h}] = {{')
    out += [f'    "{r}",' for r in rows]
    out.append('};')
    out.append(f'// from ' + ', '.join(f'#{r:02X}{g:02X}{b:02X}' for r, g, b in colours))
    out.append(f'inline constexpr uint8_t {lower}_colours[{len(colours)}] = {{' +
               ', '.join(f'0x{n:02X}' for n in nes_colours(colours)) + '};')
    out.append(f'inline constexpr Sprite {name}{{{w}, {h}, {lower}_rows, {lower}_colours}};')
    out.append('')
out.append('}  // namespace custom_sprite')
open(OUT, 'w').write('\n'.join(out) + '\n')
print(f'wrote {OUT}')
